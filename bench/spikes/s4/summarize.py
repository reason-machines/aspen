#!/usr/bin/env python3
"""Turn results/*.jsonl into the Markdown tables in results/summary.md.

usage: summarize.py [results-dir]   (default: results/ next to this file)

When the same run appears more than once, the run measured at the lowest
load average is kept: other tenants on a shared machine inflate wall time,
while CPU time and memory barely move.
"""
import json, pathlib, sys

here = pathlib.Path(__file__).resolve().parent
results = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else here / "results"


def load(name):
    path = results / name
    if not path.exists():
        return []
    best = {}
    for line in path.read_text().splitlines():
        r = json.loads(line)
        key = (r["pack"], r["run"])
        load_avg = r["measured"].get("loadavg_1m_before", 99)
        if key not in best or load_avg < best[key]["measured"].get("loadavg_1m_before", 99):
            best[key] = r
    return list(best.values())


def cpu(r):
    return r["measured"]["user_s"] + r["measured"]["sys_s"]


def mb(n):
    return f"{n / 1e6:,.1f}" if n < 1e9 else f"{n / 1e9:,.2f} G"


def size(n):
    if n < 1e3:
        return f"{n} B"
    if n < 1e6:
        return f"{n / 1e3:.1f} kB"
    if n < 1e9:
        return f"{n / 1e6:.1f} MB"
    return f"{n / 1e9:.2f} GB"


out = []
for name in ("linux.jsonl", "git.jsonl"):
    rows = load(name)
    if not rows:
        continue
    pack_bytes = next(r["pack_bytes"] for r in rows if "pack_bytes" in r)
    objects = next(r["objects"] for r in rows if "objects" in r)
    out.append(f"### {name[:-6]}: {size(pack_bytes)} pack, {objects:,} objects\n")
    out.append("| Run | Wall s | CPU s | MB per CPU-s | Heap (RssAnon) MiB | Mapped file MiB | Load before |")
    out.append("|---|---:|---:|---:|---:|---:|---:|")
    for r in sorted(rows, key=lambda r: r["run"]):
        m = r["measured"]
        out.append(
            f"| `{r['run']}` | {m['wall_s']:.1f} | {cpu(r):.1f} | {pack_bytes / 1e6 / cpu(r):.0f} "
            f"| {m['peak_rss_anon_mib']:,.0f} | {m['peak_rss_file_mib']:,.0f} | {m['loadavg_1m_before']:.1f} |"
        )
    split = [r for r in rows if "pass1_stream_s" in r]
    if split:
        out.append("\nIndex stages split at the last input byte (wall seconds):\n")
        out.append("| Run | Pass 1: receive + parse | After: re-hash, resolve deltas, write `.idx` |")
        out.append("|---|---:|---:|")
        for r in sorted(split, key=lambda r: r["run"]):
            out.append(f"| `{r['run']}` | {r['pass1_stream_s']:.1f} | {r['pass2_resolve_and_write_s']:.1f} |")
    out.append("")

thin = load("thin.jsonl")
if thin:
    packs = sorted({r["pack"] for r in thin}, key=lambda p: int(p.split("-")[1].split(".")[0]))
    by = {(r["pack"], r["run"].rsplit("-t", 1)[0]): r for r in thin}
    out.append("### Thin-pack completion against the Linux pack\n")
    out.append(
        "| Push (first-parent commits) | Received | Objects in | Bases added | Entry reads (p50/p99/max per base) "
        "| Stored, gix | Stored, `git --fix-thin` | gix wall / CPU s | gix heap MiB | git wall / CPU s | git heap MiB "
        "| Re-hash / + copy s |"
    )
    out.append("|---|---:|---:|---:|---|---:|---:|---:|---:|---:|---:|---:|")
    for p in packs:
        g, s = by.get((p, "gix-thin")), by.get((p, "git-fix-thin"))
        h, hc = by.get((p, "rehash")), by.get((p, "rehash+copy"))
        lk = g["base_lookups"]
        per = lk["entries_read_per_base"]
        n = p.split("-")[1].split(".")[0]
        objects_in = g["objects"] - lk["found"]
        out.append(
            f"| {n} | {size(g['pack_bytes_in'])} | {objects_in:,} | {lk['found']:,} "
            f"| {lk['entries_read_total']:,} ({per['p50']}/{per['p99']}/{per['max']}) "
            f"| {size(g['pack_bytes_out'])} ({g['pack_bytes_out'] / g['pack_bytes_in']:.1f}x) "
            f"| {size(s['pack_bytes_out'])} ({s['pack_bytes_out'] / s['pack_bytes_in']:.1f}x) "
            f"| {g['measured']['wall_s']:.2f} / {cpu(g):.1f} | {g['measured']['peak_rss_anon_mib']:,.0f} "
            f"| {s['measured']['wall_s']:.2f} / {cpu(s):.1f} | {s['measured']['peak_rss_anon_mib']:,.0f} "
            f"| {h['measured']['wall_s']:.2f} / {hc['measured']['wall_s']:.2f} |"
        )
    out.append("")

text = "<!-- Generated by summarize.py from results/*.jsonl; do not edit by hand. -->\n\n" + "\n".join(out)
(results / "summary.md").write_text(text)
print(text)
